#!/usr/bin/env node
// Builds the public town list from admin/mission-towns.json (Census TIGER 2024,
// all 351 Massachusetts municipalities). admin/ sits behind Cloudflare Access,
// so the homepage cannot read it; this writes two copies it can use:
//
//   js/ma-towns.json          the browser copy: name -> county code, the county
//                             names and the aliases map. No geometry.
//   functions/api/_ma_towns.js the same names for the server (request-sample.js
//                             accepts only these).
//
// Run from the repo root after admin/mission-towns.json changes:
//   node scripts/build-ma-towns.mjs
// test/ma-towns.test.mjs fails when either output drifts from the source.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = "admin/mission-towns.json";
export const PUBLIC_OUT = "js/ma-towns.json";
export const SERVER_OUT = "functions/api/_ma_towns.js";

export function buildPublic(src) {
  const towns = {};
  for (const [name, t] of Object.entries(src.towns)) towns[name] = t.c;
  return JSON.stringify({
    note: "Generated by scripts/build-ma-towns.mjs from " + SOURCE + ". Do not edit by hand.",
    attribution: src.attribution,
    counties: src.counties,
    aliases: src.aliases,
    towns,
  }) + "\n";
}

export function buildServer(src) {
  const names = Object.keys(src.towns);
  return "// Generated by scripts/build-ma-towns.mjs from " + SOURCE + ". Do not edit by hand.\n"
    + "// The " + names.length + " Massachusetts municipalities (Census TIGER 2024), canonical names only.\n"
    + "export const MA_TOWN_NAMES = Object.freeze([\n"
    + names.map((n) => "  " + JSON.stringify(n) + ",\n").join("")
    + "]);\n";
}

export function readSource(root = REPO) {
  return JSON.parse(fs.readFileSync(path.join(root, SOURCE), "utf8"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = readSource();
  fs.writeFileSync(path.join(REPO, PUBLIC_OUT), buildPublic(src));
  fs.writeFileSync(path.join(REPO, SERVER_OUT), buildServer(src));
  console.log("wrote " + PUBLIC_OUT + " and " + SERVER_OUT + ": " + Object.keys(src.towns).length + " towns");
}
